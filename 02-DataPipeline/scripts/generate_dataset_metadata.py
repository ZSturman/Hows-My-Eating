#!/usr/bin/env python3
"""
Generate dataset metadata documentation.

This script scans the raw data sessions and generates:
1. A DATASET.md file with a formatted table of all sessions
2. Individual _metadata.txt files in each session folder

Usage:
    python generate_dataset_metadata.py
"""

import argparse
from pathlib import Path
from datetime import datetime
import pandas as pd


def parse_session_name(folder_name: str) -> tuple[str, str]:
    """
    Parse session folder name to extract label and timestamp.
    
    Examples:
        "Eating-20251123-055649" -> ("Eating", "2025-11-23 05:56:49")
        "Not-eating-20251203-061305" -> ("Not-eating", "2025-12-03 06:13:05")
    """
    parts = folder_name.split('-')
    if len(parts) >= 4:
        label = parts[0]  # "Eating" or "Not"
        if label == "Not" and len(parts) >= 5:
            label = f"{parts[0]}-{parts[1]}"  # "Not-eating"
            date_str = parts[2]
            time_str = parts[3]
        else:
            date_str = parts[1]
            time_str = parts[2]
        
        # Parse date: YYYYMMDD -> YYYY-MM-DD
        date_formatted = f"{date_str[:4]}-{date_str[4:6]}-{date_str[6:8]}"
        # Parse time: HHMMSS -> HH:MM:SS
        time_formatted = f"{time_str[:2]}:{time_str[2:4]}:{time_str[4:6]}"
        
        return label, f"{date_formatted} {time_formatted}"
    
    return "Unknown", "Unknown"


def analyze_session(session_dir: Path) -> dict:
    """
    Analyze a single data session folder.
    
    Returns dict with:
        - name: folder name
        - label: Eating or Not-eating
        - date: collection timestamp
        - csv_file: motion CSV filename
        - video_file: video filename (if exists)
        - total_samples: number of CSV rows
        - duration_sec: duration in seconds
        - eating_samples: count of True labels
        - not_eating_samples: count of False labels
    """
    name = session_dir.name
    label, date = parse_session_name(name)
    
    # Find CSV file
    csv_files = list(session_dir.glob("*.csv"))
    if not csv_files:
        return {
            "name": name,
            "label": label,
            "date": date,
            "error": "No CSV file found"
        }
    
    csv_file = csv_files[0]
    
    # Find video file
    video_files = list(session_dir.glob("*.mov")) + list(session_dir.glob("*.mp4"))
    video_file = video_files[0].name if video_files else "None"
    
    # Analyze CSV
    try:
        df = pd.read_csv(csv_file)
        total_samples = len(df)
        
        # Calculate duration (assuming timestamp column exists)
        timestamp_cols = ['timestamp', 'time', 'ts', 'datetime']
        timestamp_col = None
        for col in timestamp_cols:
            if col in df.columns:
                timestamp_col = col
                break
        
        if timestamp_col and len(df) > 1:
            duration_sec = df[timestamp_col].iloc[-1] - df[timestamp_col].iloc[0]
        else:
            duration_sec = 0
        
        # Count labels
        label_col = 'label'
        if label_col in df.columns:
            eating_samples = int((df[label_col].astype(bool)).sum())
            not_eating_samples = total_samples - eating_samples
        else:
            eating_samples = 0
            not_eating_samples = 0
        
        return {
            "name": name,
            "label": label,
            "date": date,
            "csv_file": csv_file.name,
            "video_file": video_file,
            "total_samples": total_samples,
            "duration_sec": duration_sec,
            "eating_samples": eating_samples,
            "not_eating_samples": not_eating_samples,
        }
    
    except Exception as e:
        return {
            "name": name,
            "label": label,
            "date": date,
            "error": str(e)
        }


def write_session_metadata(session_dir: Path, metadata: dict) -> None:
    """Write _metadata.txt file in session directory."""
    output_path = session_dir / "_metadata.txt"
    
    content = f"""# Session Metadata
# Auto-generated by generate_dataset_metadata.py

Session Name: {metadata['name']}
Label: {metadata['label']}
Collection Date: {metadata['date']}
CSV File: {metadata.get('csv_file', 'N/A')}
Video File: {metadata.get('video_file', 'None (excluded from git)')}
Total Samples: {metadata.get('total_samples', 'N/A')}
Duration: {metadata.get('duration_sec', 0):.1f} seconds ({metadata.get('duration_sec', 0) / 60:.1f} minutes)
Eating Samples: {metadata.get('eating_samples', 'N/A')}
Not-Eating Samples: {metadata.get('not_eating_samples', 'N/A')}

# Quality Notes
# (Add manual notes here about recording quality, environmental conditions, etc.)
"""
    
    with open(output_path, 'w') as f:
        f.write(content)


def generate_dataset_markdown(sessions: list[dict], output_path: Path) -> None:
    """Generate DATASET.md with formatted table."""
    
    # Calculate totals
    total_sessions = len(sessions)
    eating_sessions = sum(1 for s in sessions if s['label'] == 'Eating')
    not_eating_sessions = total_sessions - eating_sessions
    total_duration_sec = sum(s.get('duration_sec', 0) for s in sessions)
    total_samples = sum(s.get('total_samples', 0) for s in sessions)
    
    content = f"""# ChewSense Dataset

This dataset contains motion sensor data collected from AirPods for chewing detection.

## Dataset Statistics

- **Total Sessions**: {total_sessions}
- **Eating Sessions**: {eating_sessions}
- **Not-Eating Sessions**: {not_eating_sessions}
- **Total Duration**: {total_duration_sec / 3600:.2f} hours
- **Total Samples**: {total_samples:,}

## Data Collection

Data is collected using the ChewSense Data Collection app (available on the [App Store](https://apps.apple.com/us/app/chew-sense-collect-and-label/id6755277802)).

Each session consists of:
- **CSV file**: Motion sensor data (accelerometer and gyroscope) with labels
- **Video file**: Synchronized video recording (excluded from git, see .gitignore)

## Sessions

| Session Name | Label | Date | Duration (min) | Total Samples | Eating | Not-Eating |
|-------------|-------|------|----------------|---------------|--------|------------|
"""
    
    # Sort sessions by date
    sessions_sorted = sorted(sessions, key=lambda x: x.get('date', ''))
    
    for session in sessions_sorted:
        if 'error' in session:
            content += f"| {session['name']} | {session['label']} | {session['date']} | ERROR | ERROR | - | - |\n"
        else:
            duration_min = session.get('duration_sec', 0) / 60
            content += (
                f"| {session['name']} | {session['label']} | {session['date']} | "
                f"{duration_min:.1f} | {session['total_samples']:,} | "
                f"{session['eating_samples']:,} | {session['not_eating_samples']:,} |\n"
            )
    
    content += f"""
## Data Format

Each CSV file contains the following columns:
- `timestamp`: Device timestamp (seconds since boot)
- `ax`, `ay`, `az`: Accelerometer data (g)
- `gx`, `gy`, `gz`: Gyroscope data (rad/s)
- `label`: Boolean label (true = eating, false = not eating)

## Collection Protocol

- **Eating sessions**: User performs actual eating activities while wearing AirPods, marking chewing periods with the app
- **Not-eating sessions**: User performs various daily activities (talking, walking, working, etc.) without eating

## Data Quality

- All sessions use AirPods Pro or AirPods Max with motion sensors
- Synchronized video allows for precise labeling verification
- Motion data sampled at ~50 Hz (actual rate varies slightly)

## Usage

To add new data:
1. Use the ChewSense Data Collection app to record sessions
2. Export sessions and place in `data/raw_sessions/`
3. Run `python main.py` to process and transform new data
4. Regenerate this file with: `python scripts/generate_dataset_metadata.py`

---

*Last updated: {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}*
"""
    
    with open(output_path, 'w') as f:
        f.write(content)
    
    print(f"✅ Generated {output_path}")


def main():
    parser = argparse.ArgumentParser(
        description="Generate dataset metadata documentation"
    )
    parser.add_argument(
        "--data-dir",
        type=Path,
        default=Path("data/raw_sessions"),
        help="Directory containing session folders"
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("DATASET.md"),
        help="Output markdown file"
    )
    parser.add_argument(
        "--skip-metadata-files",
        action="store_true",
        help="Skip writing individual _metadata.txt files"
    )
    
    args = parser.parse_args()
    
    # Find all session directories
    data_dir = args.data_dir
    if not data_dir.exists():
        print(f"❌ Data directory not found: {data_dir}")
        return
    
    session_dirs = [d for d in data_dir.iterdir() if d.is_dir() and not d.name.startswith('.')]
    
    if not session_dirs:
        print(f"❌ No session directories found in {data_dir}")
        return
    
    print(f"Found {len(session_dirs)} sessions in {data_dir}")
    
    # Analyze all sessions
    sessions = []
    for session_dir in sorted(session_dirs):
        print(f"Analyzing {session_dir.name}...")
        metadata = analyze_session(session_dir)
        sessions.append(metadata)
        
        # Write individual metadata file
        if not args.skip_metadata_files:
            write_session_metadata(session_dir, metadata)
    
    # Generate markdown
    generate_dataset_markdown(sessions, args.output)
    
    print(f"\n📊 Dataset Summary:")
    print(f"   Total sessions: {len(sessions)}")
    print(f"   Eating: {sum(1 for s in sessions if s['label'] == 'Eating')}")
    print(f"   Not-eating: {sum(1 for s in sessions if s['label'] == 'Not-eating')}")
    print(f"   Total duration: {sum(s.get('duration_sec', 0) for s in sessions) / 3600:.2f} hours")


if __name__ == "__main__":
    main()
